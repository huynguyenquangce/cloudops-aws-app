#!/usr/bin/env python3
"""Validate exams/exam-*.json and bundle them into exams.js (lazy-loaded by index.html).

Source format (exams/exam-N.json):
  {"id": N, "title": {"vi": "...", "en": "..."}, "q": [question, ...]}
question: {"d": 1-5, "task": "1.2", "ref": "<section id in index.html>", "type": "single"|"multi",
           "pick": k, "q": {vi,en}, "o": [{vi,en}...], "a": [idx...], "why": [{vi,en}...], "ex": {vi,en}}
Run: python3 tools/build_exams.py
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
html = (ROOT / 'index.html').read_text(encoding='utf-8')
ids = set(re.findall(r'<section class="topic" id="([^"]+)"', html))

def bil(x, where):
    assert isinstance(x, dict) and x.get('vi', '').strip() and x.get('en', '').strip(), f'{where}: needs non-empty vi+en'

exams = []
for f in sorted((ROOT / 'exams').glob('exam-*.json')):
    ex = json.loads(f.read_text(encoding='utf-8'))
    bil(ex['title'], f.name)
    for i, q in enumerate(ex['q'], 1):
        w = f'{f.name} Q{i}'
        assert q['d'] in (1, 2, 3, 4, 5), w
        assert re.fullmatch(r'[1-5]\.[1-3]', q['task']) and q['task'][0] == str(q['d']), f'{w}: task'
        assert q['ref'] in ids, f'{w}: ref "{q["ref"]}" is not a section id'
        n = len(q['o'])
        if q['type'] == 'single':
            assert q['pick'] == 1 and n == 4, f'{w}: single needs 4 options'
        else:
            assert q['type'] == 'multi' and q['pick'] >= 2 and n >= 5, f'{w}: multi needs pick>=2, >=5 options'
        assert len(q['a']) == q['pick'] == len(set(q['a'])) and all(0 <= a < n for a in q['a']), f'{w}: answers'
        assert len(q['why']) == n, f'{w}: why count'
        for k in ['q', 'ex']: bil(q[k], f'{w}.{k}')
        for k, o in enumerate(q['o']): bil(o, f'{w}.o{k}'); bil(q['why'][k], f'{w}.why{k}')
    exams.append({'id': ex['id'], 'title': ex['title'], 'q': [{k: q[k] for k in ('d','task','ref','type','pick','q','o','a','why','ex')} for q in ex['q']]})
    print(f'{f.name}: {len(ex["q"])} questions OK')

out = ROOT / 'exams.js'
out.write_text('/* generated by tools/build_exams.py from exams/*.json — do not edit by hand */\nwindow.CLOUDOPS_EXAMS=' +
               json.dumps({'exams': exams}, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'wrote {out.name} ({out.stat().st_size // 1024} KB)')
